-- Hierarquia de atendimentos com herança JOINED: os campos comuns vão para a tabela atendimento,
-- e consulta e internacao passam a ter como chave o id do atendimento.
--
-- Consultas e internações tinham sequências de id próprias, então os ids antigos colidem entre si.
-- Cada registro ganha um novo id em atendimento; origem e id_origem guardam o vínculo durante a
-- conversão e são removidas ao final.

CREATE TABLE atendimento (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id                 BIGINT        NOT NULL,
    profissional_responsavel_id BIGINT        NOT NULL,
    observacoes                 VARCHAR(1000),
    origem                      VARCHAR(20),
    id_origem                   BIGINT,
    CONSTRAINT fk_atendimento_paciente FOREIGN KEY (paciente_id) REFERENCES paciente (id),
    CONSTRAINT fk_atendimento_profissional FOREIGN KEY (profissional_responsavel_id) REFERENCES profissional_saude (id)
);

INSERT INTO atendimento (paciente_id, profissional_responsavel_id, observacoes, origem, id_origem)
SELECT paciente_id, profissional_responsavel_id, observacoes, 'CONSULTA', id FROM consulta;

INSERT INTO atendimento (paciente_id, profissional_responsavel_id, observacoes, origem, id_origem)
SELECT paciente_id, profissional_responsavel_id, observacoes, 'INTERNACAO', id FROM internacao;

-- Consulta ---------------------------------------------------------------------------------------

ALTER TABLE consulta DROP CONSTRAINT fk_consulta_paciente;
ALTER TABLE consulta DROP CONSTRAINT fk_consulta_profissional;
ALTER TABLE consulta DROP CONSTRAINT ck_consulta_status;
DROP INDEX idx_consulta_profissional_data;
DROP INDEX idx_consulta_paciente_data;

-- O id passa a vir de atendimento. A troca é feita em duas etapas, passando por valores negativos,
-- para que nenhum id novo colida com um id antigo ainda não convertido.
ALTER TABLE consulta ALTER COLUMN id DROP IDENTITY;
UPDATE consulta SET id = -id;
UPDATE consulta SET id = (SELECT a.id FROM atendimento a WHERE a.origem = 'CONSULTA' AND a.id_origem = -consulta.id);

ALTER TABLE consulta DROP COLUMN paciente_id;
ALTER TABLE consulta DROP COLUMN profissional_responsavel_id;
ALTER TABLE consulta DROP COLUMN observacoes;

ALTER TABLE consulta RENAME COLUMN status TO situacao;
UPDATE consulta SET situacao = 'CONCLUIDA' WHERE situacao = 'REALIZADA';

ALTER TABLE consulta ADD CONSTRAINT ck_consulta_situacao
    CHECK (situacao IN ('AGENDADA', 'CONFIRMADA', 'EM_ATENDIMENTO', 'CONCLUIDA', 'CANCELADA', 'NAO_COMPARECEU'));
ALTER TABLE consulta ADD CONSTRAINT fk_consulta_atendimento FOREIGN KEY (id) REFERENCES atendimento (id);

-- Verificação de conflito de horários: filtra as consultas da data e junta com atendimento pelo id.
CREATE INDEX idx_consulta_data ON consulta (data);

CREATE TABLE consulta_rotina (
    id BIGINT PRIMARY KEY,
    CONSTRAINT fk_consulta_rotina_consulta FOREIGN KEY (id) REFERENCES consulta (id)
);

CREATE TABLE consulta_especializada (
    id           BIGINT      PRIMARY KEY,
    area_atuacao VARCHAR(30) NOT NULL,
    CONSTRAINT fk_consulta_especializada_consulta FOREIGN KEY (id) REFERENCES consulta (id)
);

-- Não havia modalidade na Sprint 1: todas as consultas existentes passam a ser de rotina.
INSERT INTO consulta_rotina (id) SELECT id FROM consulta;

-- Internação -------------------------------------------------------------------------------------

ALTER TABLE internacao DROP CONSTRAINT fk_internacao_paciente;
ALTER TABLE internacao DROP CONSTRAINT fk_internacao_profissional;
DROP INDEX idx_internacao_paciente;
DROP INDEX idx_internacao_profissional;

ALTER TABLE internacao ALTER COLUMN id DROP IDENTITY;
UPDATE internacao SET id = -id;
UPDATE internacao SET id = (SELECT a.id FROM atendimento a WHERE a.origem = 'INTERNACAO' AND a.id_origem = -internacao.id);

ALTER TABLE internacao DROP COLUMN paciente_id;
ALTER TABLE internacao DROP COLUMN profissional_responsavel_id;
ALTER TABLE internacao DROP COLUMN observacoes;

ALTER TABLE internacao ADD CONSTRAINT fk_internacao_atendimento FOREIGN KEY (id) REFERENCES atendimento (id);

-- Atendimento ------------------------------------------------------------------------------------

ALTER TABLE atendimento DROP COLUMN origem;
ALTER TABLE atendimento DROP COLUMN id_origem;

-- Histórico do paciente e agenda do profissional.
CREATE INDEX idx_atendimento_paciente ON atendimento (paciente_id);
CREATE INDEX idx_atendimento_profissional ON atendimento (profissional_responsavel_id);
