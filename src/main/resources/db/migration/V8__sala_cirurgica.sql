-- Salas cirúrgicas, e a sala e a duração prevista de cada procedimento cirúrgico.

CREATE TABLE sala_cirurgica (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificacao VARCHAR(30) NOT NULL,
    ativa         BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_sala_cirurgica_identificacao UNIQUE (identificacao)
);

ALTER TABLE procedimento_cirurgico ADD COLUMN sala_cirurgica_id BIGINT;
ALTER TABLE procedimento_cirurgico ADD COLUMN duracao_prevista_minutos INTEGER;

-- Os procedimentos já cadastrados não tinham sala nem duração: passam para uma sala padrão, com 60 minutos.
-- O DISTINCT cria a sala uma única vez, e só quando há procedimentos; num banco novo nenhuma sala é criada.
-- O CAST fixa o tipo do texto literal, para que o comando se comporte igual no PostgreSQL e no H2.
INSERT INTO sala_cirurgica (identificacao)
SELECT DISTINCT CAST('Sala padrão' AS VARCHAR(30)) FROM procedimento_cirurgico;

UPDATE procedimento_cirurgico
SET sala_cirurgica_id = (SELECT id FROM sala_cirurgica WHERE identificacao = 'Sala padrão'),
    duracao_prevista_minutos = 60;

ALTER TABLE procedimento_cirurgico ALTER COLUMN sala_cirurgica_id SET NOT NULL;
ALTER TABLE procedimento_cirurgico ALTER COLUMN duracao_prevista_minutos SET NOT NULL;

ALTER TABLE procedimento_cirurgico ADD CONSTRAINT fk_procedimento_cirurgico_sala
    FOREIGN KEY (sala_cirurgica_id) REFERENCES sala_cirurgica (id);
-- Os mesmos limites de ProcedimentoCirurgico.DURACAO_MINIMA_MINUTOS e DURACAO_MAXIMA_MINUTOS.
ALTER TABLE procedimento_cirurgico ADD CONSTRAINT ck_procedimento_cirurgico_duracao
    CHECK (duracao_prevista_minutos BETWEEN 15 AND 720);

-- Busca de procedimentos pelo início previsto, numa sala (disponibilidade da sala) ou em todas (listagem por data).
CREATE INDEX idx_procedimento_cirurgico_sala ON procedimento_cirurgico (sala_cirurgica_id, data_hora_prevista);
CREATE INDEX idx_procedimento_cirurgico_prevista ON procedimento_cirurgico (data_hora_prevista);
